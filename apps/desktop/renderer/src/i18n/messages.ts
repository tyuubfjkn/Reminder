export const messages: Record<Locale, Record<MessageKey, string>> = { 'en-US': enUS, 'zh-CN': zhCN };

export function translate(locale: Locale, key: MessageKey, vars: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match);
}

const fieldKeys: Record<string, MessageKey> = {
  title: 'error.title', notes: 'error.notes', estimatedMinutes: 'error.estimate',
  deadline: 'error.deadline', priority: 'error.priority', timeZone: 'error.timeZone', locale: 'error.locale'
};

export function errorKey(error: Failure): MessageKey {
  switch (error.code) {
    case 'VALIDATION_ERROR': return (error.field && fieldKeys[error.field]) || 'error.validation';
    case 'NOT_FOUND': return 'error.notFound';
    case 'CONFLICT': return 'error.conflict';
    case 'STORAGE_ERROR': return 'error.storage';
    case 'FORBIDDEN': return 'error.forbidden';
    case 'UNKNOWN_METHOD': return 'error.unknownMethod';
    default: return 'error.ipc';
  }
}

export function errorMessage(locale: Locale, error: Failure): string {
  return translate(locale, errorKey(error));
}
